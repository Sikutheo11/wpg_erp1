class CustomerForm(forms.ModelForm):
    """
    Create or update an enterprise customer.
    """

    class Meta:
        model = Customer

        fields = [
            "user",
            "customer_type",
            "full_name",
            "company_name",
            "phone",
            "email",
            "address",
            "tax_number",
            "credit_limit",
            "is_active",
        ]

        widgets = {
            "user": forms.Select(
                attrs={
                    "class": "form-select",
                }
            ),
            "customer_type": forms.Select(
                attrs={
                    "class": "form-select",
                }
            ),
            "full_name": forms.TextInput(
                attrs={
                    "class": "form-control",
                    "placeholder": "Customer full name",
                }
            ),
            "company_name": forms.TextInput(
                attrs={
                    "class": "form-control",
                    "placeholder": "Company or institution name",
                }
            ),
            "phone": forms.TextInput(
                attrs={
                    "class": "form-control",
                    "placeholder": "Phone number",
                }
            ),
            "email": forms.EmailInput(
                attrs={
                    "class": "form-control",
                    "placeholder": "Email address",
                }
            ),
            "address": forms.Textarea(
                attrs={
                    "class": "form-control",
                    "rows": 3,
                    "placeholder": "Customer address",
                }
            ),
            "tax_number": forms.TextInput(
                attrs={
                    "class": "form-control",
                    "placeholder": "Tax identification number",
                }
            ),
            "credit_limit": forms.NumberInput(
                attrs={
                    "class": "form-control",
                    "min": "0",
                    "step": "0.01",
                }
            ),
            "is_active": forms.CheckboxInput(
                attrs={
                    "class": "form-check-input",
                }
            ),
        }

    def clean_credit_limit(self):
        credit_limit = self.cleaned_data.get(
            "credit_limit"
        )

        if credit_limit is not None and credit_limit < 0:
            raise forms.ValidationError(
                "Credit limit cannot be negative."
            )

        return credit_limit

    def clean(self):
        cleaned_data = super().clean()

        full_name = (
            cleaned_data.get("full_name")
            or ""
        ).strip()

        company_name = (
            cleaned_data.get("company_name")
            or ""
        ).strip()

        user = cleaned_data.get("user")

        if not full_name and not company_name and not user:
            raise forms.ValidationError(
                (
                    "Provide a full name, company name "
                    "or linked user account."
                )
            )

        return cleaned_data


