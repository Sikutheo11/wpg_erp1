class SalesQuotationForm(forms.ModelForm):
    """
    Customer-facing quotation header.

    Status is excluded because it is managed by WorkflowService.
    Quotation number and totals are generated by the service layer.
    """

    class Meta:
        model = SalesQuotation

        fields = [
            "customer",
            "business_unit",
            "order_type",
            "quotation_date",
            "valid_until",
            "discount",
            "tax",
            "notes",
        ]

        widgets = {
            "customer": forms.Select(
                attrs={
                    "class": "form-select",
                }
            ),
            "business_unit": forms.Select(
                attrs={
                    "class": "form-select",
                }
            ),
            "order_type": forms.Select(
                attrs={
                    "class": "form-select",
                }
            ),
            "quotation_date": forms.DateInput(
                attrs={
                    "class": "form-control",
                    "type": "date",
                },
                format="%Y-%m-%d",
            ),
            "valid_until": forms.DateInput(
                attrs={
                    "class": "form-control",
                    "type": "date",
                },
                format="%Y-%m-%d",
            ),
            "discount": forms.NumberInput(
                attrs={
                    "class": "form-control quotation-discount",
                    "min": "0",
                    "step": "0.01",
                }
            ),
            "tax": forms.NumberInput(
                attrs={
                    "class": "form-control quotation-tax",
                    "min": "0",
                    "step": "0.01",
                }
            ),
            "notes": forms.Textarea(
                attrs={
                    "class": "form-control",
                    "rows": 4,
                    "placeholder": (
                        "Customer requirements, delivery terms "
                        "or quotation notes..."
                    ),
                }
            ),
        }

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)

        self.fields["customer"].queryset = (
            Customer.objects
            .filter(is_active=True)
            .order_by(
                "company_name",
                "full_name",
                "phone",
            )
        )

        self.fields["customer"].empty_label = (
            "Select customer"
        )

        self.fields["business_unit"].empty_label = (
            "Select business unit"
        )

        self.fields["order_type"].empty_label = (
            "Select order type"
        )

        self.fields["quotation_date"].input_formats = [
            "%Y-%m-%d",
        ]

        self.fields["valid_until"].input_formats = [
            "%Y-%m-%d",
        ]

    def clean_discount(self):
        discount = self.cleaned_data.get(
            "discount"
        )

        if discount is not None and discount < 0:
            raise forms.ValidationError(
                "Discount cannot be negative."
            )

        return discount

    def clean_tax(self):
        tax = self.cleaned_data.get(
            "tax"
        )

        if tax is not None and tax < 0:
            raise forms.ValidationError(
                "Tax cannot be negative."
            )

        return tax

    def clean(self):
        cleaned_data = super().clean()

        quotation_date = cleaned_data.get(
            "quotation_date"
        )

        valid_until = cleaned_data.get(
            "valid_until"
        )

        if (
            quotation_date
            and valid_until
            and valid_until < quotation_date
        ):
            self.add_error(
                "valid_until",
                (
                    "Valid-until date cannot be before "
                    "the quotation date."
                ),
            )

        return cleaned_data


