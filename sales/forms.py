class SalesQuotationItemForm(forms.ModelForm):
    """
    One quotation line.

    A line may use:
    - a published inventory product; or
    - a custom product/service name.
    """

    class Meta:
        model = SalesQuotationItem

        fields = [
            "product",
            "product_name",
            "quantity",
            "unit_price",
            "specifications",
        ]

        widgets = {
            "product": forms.Select(
                attrs={
                    "class": (
                        "form-select quotation-product"
                    ),
                }
            ),
            "product_name": forms.TextInput(
                attrs={
                    "class": (
                        "form-control "
                        "quotation-product-name"
                    ),
                    "placeholder": (
                        "Custom product or service"
                    ),
                }
            ),
            "quantity": forms.NumberInput(
                attrs={
                    "class": (
                        "form-control quotation-quantity"
                    ),
                    "min": "1",
                    "step": "1",
                    "value": "1",
                }
            ),
            "unit_price": forms.NumberInput(
                attrs={
                    "class": (
                        "form-control quotation-price"
                    ),
                    "min": "0",
                    "step": "0.01",
                }
            ),
            "specifications": forms.Textarea(
                attrs={
                    "class": "form-control",
                    "rows": 2,
                    "placeholder": (
                        "Dimensions, material, color, "
                        "scope or other specifications"
                    ),
                }
            ),
        }

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)

        # All products approved for sale appear
        # regardless of quotation business unit.
        self.fields["product"].queryset = (
            Product.objects
            .filter(is_published=True)
            .order_by("name")
        )

        self.fields["product"].empty_label = (
            "Select published product"
        )

        self.fields["product"].required = False
        self.fields["product_name"].required = False

    def clean(self):
        cleaned_data = super().clean()

        if cleaned_data.get("DELETE"):
            return cleaned_data

        product = cleaned_data.get("product")

        product_name = (
            cleaned_data.get("product_name")
            or ""
        ).strip()

        quantity = cleaned_data.get("quantity")
        unit_price = cleaned_data.get(
            "unit_price"
        )

        if not product and not product_name:
            raise forms.ValidationError(
                (
                    "Select a published product or enter "
                    "a custom product/service name."
                )
            )

        if quantity is not None and quantity <= 0:
            self.add_error(
                "quantity",
                (
                    "Quantity must be greater than zero."
                ),
            )

        if unit_price is not None and unit_price < 0:
            self.add_error(
                "unit_price",
                (
                    "Unit price cannot be negative."
                ),
            )

        return cleaned_data


